"""AST-backed SQL policy used at both sides of the Wren planning boundary.

The sidecar receives SQL produced by an untrusted model.  A token scanner is
not sufficient here: PostgreSQL permits comments, dollar quoted strings, CTEs,
and nested expressions that can hide a second statement or a data-changing
operation.  This module therefore parses with sqlglot's PostgreSQL grammar and
checks the resulting tree.  The caller may additionally provide the physical
objects derived from the MDL manifest; when it does, every non-CTE table must
match that allowlist.

The module intentionally exposes only policy decisions and never includes the
submitted SQL in an exception message.  That keeps the same no-leak invariant
as the framed RPC boundary.
"""

