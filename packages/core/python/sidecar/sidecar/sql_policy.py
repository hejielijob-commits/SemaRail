_QUERY_ROOT_NAMES = frozenset({"Select", "Union", "Intersect", "Except"})


@dataclass(frozen=True, slots=True)
class PhysicalTable:
    """One physical table permitted by the MDL manifest."""

    catalog: str | None
    schema: str | None
    table: str

    def normalized(self) -> tuple[str | None, str | None, str]:
        return (
            self.catalog.lower() if self.catalog else None,
            self.schema.lower() if self.schema else None,
            self.table.lower(),
        )


@dataclass(frozen=True, slots=True)
class PhysicalAllowlist:
    """Canonical physical schema/table allowlist for native SQL checks."""

    tables: frozenset[PhysicalTable]

    @property
    def schemas(self) -> frozenset[str]:
        return frozenset(item.schema.lower() for item in self.tables if item.schema)

    @property
    def catalogs(self) -> frozenset[str]:
        return frozenset(item.catalog.lower() for item in self.tables if item.catalog)

    def as_dict(self) -> dict[str, Any]:
        table_rows = [
            {
                **({"catalog": item.catalog} if item.catalog else {}),
                **({"schema": item.schema} if item.schema else {}),
                "table": item.table,
            }
            for item in sorted(
                self.tables,
                key=lambda value: (
                    (value.catalog or "").lower(),
                    (value.schema or "").lower(),
                    value.table.lower(),
                ),
            )
        ]
        return {
            "catalogs": sorted(self.catalogs),
            "schemas": sorted(self.schemas),
            "tables": table_rows,
        }


def _parse_one_read_only(sql: str) -> exp.Expression:
    if not isinstance(sql, str) or not sql.strip():
        raise SqlPolicyError("query is empty")
    try:
        # parse(), unlike parse_one(), lets us reject a second statement
        # instead of silently ignoring it.  PostgreSQL handles comments and
        # dollar-quoted literals before the AST is produced.
        # Some sqlglot dialect fallbacks print an unsupported-syntax warning
        # containing the submitted SQL.  Suppress that diagnostic at this
        # boundary: SQL (and especially literal secrets) must never reach the
        # sidecar's stderr logs either.
        with contextlib.redirect_stderr(io.StringIO()):
            statements = parse(sql, read="postgres", error_level=ErrorLevel.RAISE)
    except (ParseError, SqlglotError, ValueError, TypeError) as exc:
        raise SqlPolicyError("query is not valid PostgreSQL SQL") from exc
    # sqlglot represents a trailing semicolon followed by a comment as a
    # standalone ``Semicolon`` node, and an empty trailing statement as None.
    # Those do not constitute a second executable statement.  Any additional
    # query/command node still fails closed.
    executable = [
        item
        for item in statements
        if item is not None and type(item).__name__ != "Semicolon"
    ]
    if len(executable) != 1:
        raise SqlPolicyError("multiple SQL statements are not allowed")
    statement = executable[0]
    if type(statement).__name__ not in _QUERY_ROOT_NAMES:
        raise SqlPolicyError("only SELECT or read-only query expressions are allowed")
    for node in statement.walk():
        if type(node).__name__ in _DENIED_EXPRESSION_NAMES:
            raise SqlPolicyError("query contains a denied SQL operation")
    return statement


def validate_semantic_sql(sql: str) -> str:
    """Type-check semantic SQL as one read-only PostgreSQL query."""

    _parse_one_read_only(sql)
    return sql.strip()


def _function_name(function: exp.Func) -> str:
    """Return the canonical lower-case function name for a sqlglot node."""

    if isinstance(function, exp.Anonymous):
        value = function.name
    else:
        try:
            value = function.sql_name()
        except (AttributeError, TypeError):
            value = function.name
    if not isinstance(value, str) or not value:
        value = type(function).__name__
    return value.lower()


def _check_functions(statement: exp.Expression) -> None:
    for function in statement.find_all(exp.Func):
        # sqlglot models boolean connectors (AND/OR) as Func subclasses for
        # inheritance purposes, but they are operators, not callable database
        # functions and therefore must not be looked up in the function list.
        if isinstance(function, (exp.Connector, exp.Case, exp.If, exp.Explode, exp.Unnest)):
            continue
        name = _function_name(function)
        if name in DANGEROUS_FUNCTIONS or name not in SAFE_FUNCTIONS:
            raise SqlPolicyError("query contains a function outside the allowlist")


def _cte_names(statement: exp.Expression) -> set[str]:
    names: set[str] = set()
    for cte in statement.find_all(exp.CTE):
        alias = cte.alias_or_name
        if isinstance(alias, str) and alias:
            names.add(alias.lower())
    return names


def _identifier_quoted(identifier: Any) -> bool:
    return bool(getattr(identifier, "quoted", False))


def _identifier_value(identifier: Any) -> str:
    value = getattr(identifier, "name", None)
    if isinstance(value, str):
        return value
    value = getattr(identifier, "this", identifier)
    return value if isinstance(value, str) else str(value)


def _table_parts(table: exp.Table) -> tuple[str, str | None, str | None, bool]:
    identifier = table.this
    name = _identifier_value(identifier)
    db = table.args.get("db")
    catalog = table.args.get("catalog")
    schema = _identifier_value(db) if db is not None else None
    catalog_name = _identifier_value(catalog) if catalog is not None else None
    return name, schema, catalog_name, _identifier_quoted(identifier)


def _table_matches(
    table: exp.Table,
    allowlist: PhysicalAllowlist,
) -> bool:
    name, schema, catalog, quoted = _table_parts(table)
    if not name:
        return False
    lower_name = name.lower()
    lower_schema = schema.lower() if schema else None
    lower_catalog = catalog.lower() if catalog else None
    for allowed in allowlist.tables:
        ac, ass, at = allowed.normalized()
        if at != lower_name:
            continue
        # Never let an unqualified name select an arbitrary same-named table
        # through PostgreSQL's search_path.  Wren manifests normally carry a
        # physical schema and the native plan must preserve that qualification.
        # A schema-less allowlist entry is retained only for explicit injected
        # seams whose MDL truly has no schema to authorize.
        if ass is not None and lower_schema is None:
            continue
        if lower_schema is not None and ass != lower_schema:
            continue
        if lower_catalog is not None and ac != lower_catalog:
            continue
        # Quoted identifiers are case-sensitive in PostgreSQL.  Unquoted
        # identifiers are case-folded; the normalized comparison above is the
        # safe match for generated SQL, while this exact check prevents a
        # quoted typo from being treated as the unquoted object.
        if quoted and name != allowed.table:
            continue
        if schema is not None and _identifier_quoted(table.args.get("db")):
            if schema != allowed.schema:
                continue
        if catalog is not None and _identifier_quoted(table.args.get("catalog")):
            if catalog != allowed.catalog:
                continue
        return True
    return False


def _check_tables(statement: exp.Expression, allowlist: PhysicalAllowlist) -> None:
    ctes = _cte_names(statement)
    ctes_lower = {item.lower() for item in ctes}
    for table in statement.find_all(exp.Table):
        name, schema, catalog, quoted = _table_parts(table)
        # A CTE is an in-memory query result, not a physical object.  A schema
        # or catalog qualifier can never be a CTE reference and is therefore
        # not exempted.
        cte_match = name in ctes if quoted else name.lower() in ctes_lower
        if not schema and not catalog and cte_match:
            continue
        if not _table_matches(table, allowlist):
            raise SqlPolicyError("query references an object outside the MDL allowlist")


def validate_native_sql(
    sql: str,
    *,
    allowed_physical: PhysicalAllowlist | Mapping[str, Any] | None = None,
) -> str:
    """Validate native SQL structurally and against permitted physical tables.

    ``allowed_physical`` is required by the production Wren adapter.  It is
    optional only for injected planner seams, where callers can still obtain
    AST read-only/function checks.  An explicit empty allowlist is fail-closed.
    """

    statement = _parse_one_read_only(sql)
    _check_functions(statement)
    if allowed_physical is not None:
        allowlist = (
            allowed_physical
            if isinstance(allowed_physical, PhysicalAllowlist)
            else physical_allowlist_from_dict(allowed_physical)
        )
        _check_tables(statement, allowlist)
    return sql.strip()


def physical_allowlist_from_dict(value: Mapping[str, Any]) -> PhysicalAllowlist:
    """Parse the JSON-safe ``allowedPhysical`` representation fail-closed."""

    raw_tables = value.get("tables")
    if not isinstance(raw_tables, (list, tuple)):
        return PhysicalAllowlist(frozenset())
    tables: set[PhysicalTable] = set()
    for raw in raw_tables:
        if not isinstance(raw, Mapping):
            continue
        table = raw.get("table")
        schema = raw.get("schema")
        catalog = raw.get("catalog")
        if not isinstance(table, str) or not table or len(table) > 512:
            continue
        if schema is not None and (not isinstance(schema, str) or not schema):
            continue
        if catalog is not None and (not isinstance(catalog, str) or not catalog):
            continue
        tables.add(PhysicalTable(catalog, schema, table))
    return PhysicalAllowlist(frozenset(tables))


def physical_allowlist_from_manifest(manifest: Mapping[str, Any]) -> PhysicalAllowlist:
    """Derive physical source objects from a Wren JSON MDL manifest."""

    default_catalog = manifest.get("catalog")
    if not isinstance(default_catalog, str) or not default_catalog:
        default_catalog = None
    default_schema = manifest.get("schema")
    if not isinstance(default_schema, str) or not default_schema:
        default_schema = None
    raw_models = manifest.get("models")
    tables: set[PhysicalTable] = set()
    if not isinstance(raw_models, (list, tuple)):
        return PhysicalAllowlist(frozenset())
    for model in raw_models:
        if not isinstance(model, Mapping):
            continue
        ref = model.get("tableReference", model.get("table_reference"))
        if not isinstance(ref, Mapping):
            continue
        table = ref.get("table")
        schema = ref.get("schema", default_schema)
        catalog = ref.get("catalog", ref.get("database", default_catalog))
        if not isinstance(table, str) or not table:
            continue
        if schema is not None and not isinstance(schema, str):
            schema = None
        if catalog is not None and not isinstance(catalog, str):
            catalog = None
        tables.add(PhysicalTable(catalog, schema, table))
    return PhysicalAllowlist(frozenset(tables))


def extract_table_names(sql: str) -> frozenset[str]:
    """Return unqualified table/CTE names for injected planner compatibility."""

    statement = _parse_one_read_only(sql)
    return frozenset(
        name
        for name, schema, catalog, _quoted in (
            _table_parts(table) for table in statement.find_all(exp.Table)
        )
        if name and not schema and not catalog
    )


